"""Offline conversion of the user's clothes. No Blender/editor code ships to the browser.
Requires numpy, scipy, Pillow, fast-simplification==0.1.12 (only for this export).
Run: python scripts/assets/export_pilot_wardrobe.py /path/to/upload
"""
import hashlib
import io
import json
import sys
import subprocess
from pathlib import Path
import numpy as np
from scipy.spatial import cKDTree
from PIL import Image
import fast_simplification
from blend_reader import Blend

ROOT = Path(__file__).resolve().parents[2]
SOURCE = Path(sys.argv[1])

def smooth(a, b, x):
    t = np.clip((x-a)/(b-a), 0, 1)
    return t*t*(3-2*t)

def mesh_data(v, f, colors=None):
    out = dict(vertices=np.round(v, 5).reshape(-1).tolist(), indices=f.reshape(-1).tolist())
    if colors is not None:
        out['colors'] = np.clip(np.round(colors*255), 0, 255).astype(int).reshape(-1).tolist()
    return out

def reduce(v, f, target):
    p, faces = fast_simplification.simplify(v, f, target_count=min(target, len(f)), agg=5)
    return p, faces

def mirrored(v, f):
    # Apply the artist's X mirror, reverse its winding, weld the center seam.
    other = v.copy(); other[:,0] *= -1
    vv = np.concatenate([v, other]); ff = np.concatenate([f, f[:,::-1]+len(v)])
    _, ids, mapping = np.unique(np.round(vv, 6), axis=0, return_index=True, return_inverse=True)
    return vv[ids], mapping[ff]

shirt = Blend(SOURCE/'shirts_tpl.blend')
out = {}
for name, source, budgets in [('tee','Cube.000',[2000,460]), ('hoodie','Cube.001',[2800,650])]:
    v, f, _ = shirt.mesh(source)
    v, f = mirrored(np.array(v), np.array(f))
    v = v[:,[0,2,1]]*.235
    f = f[:,[0,2,1]]  # Blender Z-up to Y-up changes handedness.
    v[:,1] += .96-v[:,1].min()
    # Align the template's forward-curved shoulders/collar with the game rig.
    v[:,2] -= .070*smooth(1.27, 1.50, v[:,1])
    x = np.abs(v[:,0]); arm = smooth(.16,.27,x)
    v[:,2] -= .010*arm
    v[:,0] = np.sign(v[:,0])*(x-np.maximum(0,x-.185)*.065)
    ease=1-smooth(.97,1.12,v[:,1])
    v[:,0]*=1+.06*ease;v[:,2]*=1+.18*ease
    v[:,1]-=.015*ease
    if name=='hoodie':
        v[:,2]+=.055*smooth(1.50,1.61,v[:,1])
    # A few millimetres of resting fabric ease, not a cloth physics simulation.
    v[:,2] += np.sin(v[:,1]*56+x*19)*.0018*(1-smooth(1.35,1.48,v[:,1]))
    levels=[]
    for budget in budgets:
        vv,ff=reduce(v,f,budget)
        # Readable ribbing follows the actual neck, sleeve and hem boundaries.
        edges=np.sort(np.concatenate([ff[:,[0,1]],ff[:,[1,2]],ff[:,[2,0]]]),axis=1)
        unique,counts=np.unique(edges,axis=0,return_counts=True)
        boundary=np.unique(unique[counts==1])
        dist=cKDTree(vv[boundary]).query(vv)[0]
        shade=.78+.22*smooth(.003,.012,dist)
        shade*=1-.035*np.cos(vv[:,0]*41+vv[:,1]*37)
        levels.append(mesh_data(vv,ff,np.repeat(shade[:,None],3,axis=1)))
    out[name]=levels

shoe=Blend(SOURCE/'sneakers.blend')
v,f,uv=shoe.mesh('Plane.007'); v=np.array(v); f=np.array(f); uv=np.array(uv)
texture=np.asarray(Image.open(io.BytesIO(shoe.packed_image('rb_r_black.PNG'))).convert('RGB'))/255
# Bake the supplied diffuse map into vertex colours, shared by GPU and Canvas.
# Supersample around each UV corner to avoid picking a seam's neighbouring island.
color=np.zeros_like(v); weight=np.zeros(len(v))
for face,uvs in zip(f,uv):
    for j,index in enumerate(face):
        q=uvs[j]*.94+uvs.mean(0)*.06
        px=int(np.clip(q[0]*texture.shape[1],0,texture.shape[1]-1))
        py=int(np.clip((1-q[1])*texture.shape[0],0,texture.shape[0]-1))
        color[index]+=texture[py,px];weight[index]+=1
color/=np.maximum(1,weight[:,None])
# The source points toe-first along +X. Use -Z in game; sole rests at Y=0.
v=np.stack([v[:,1]*.80,(v[:,2]-v[:,2].min())*.80,-v[:,0]*.80-.076],axis=1)
f=f[:,[0,2,1]]  # This coordinate transform has a negative determinant.
levels=[]
for budget in [1400,540]:
    vv,ff=reduce(v,f,budget)
    # Keep the sole on the terrain after simplification and quantization.
    vv=np.clip(vv,v.min(0),v.max(0))
    distances,ids=cKDTree(v).query(vv,k=3)
    w=1/np.maximum(distances,1e-5)**3
    cc=(color[ids]*w[:,:,None]).sum(1)/w.sum(1)[:,None]
    levels.append(mesh_data(vv,ff,cc))
out['sneaker']=levels
# Distant faces keep their silhouette without rendering thousands of subpixel triangles.
heads=json.loads((ROOT/'game/pilot-heads.js').read_text().split('export const PILOT_HEADS=')[1].rstrip(';\n'))
out['distantHeads']=[]
for head in heads:
    vv,ff=reduce(np.array(head['vertices']).reshape(-1,3),np.array(head['indices']).reshape(-1,3),600)
    out['distantHeads'].append(mesh_data(vv,ff))
header='// Adapted from the user-supplied Shirt Template and Sneakers assets.\n// See assets/licenses/README.md for sources, attribution and supplied terms.\n// Generated by scripts/assets/export_pilot_wardrobe.py; lengths are metres.\n'
(ROOT/'game/pilot-wardrobe-data.js').write_text(header+'export const PILOT_WARDROBE='+json.dumps(out,separators=(',',':'))+';\n')
manifest={'sources':{n:hashlib.sha256((SOURCE/n).read_bytes()).hexdigest() for n in ['shirts_tpl.blend','sneakers.blend']},'triangles':{k:[len(g['indices'])//3 for g in levels] for k,levels in out.items()}}
(ROOT/'game/assets/licenses/wardrobe-manifest.json').write_text(json.dumps(manifest,indent=2)+'\n')
print(json.dumps(manifest,indent=2))
subprocess.run([sys.executable,str(Path(__file__).with_name('rebake_shoe_colors.py')),str(SOURCE/'sneakers.blend')],check=True)
